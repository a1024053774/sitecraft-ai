import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ArrowRight, Mail, Phone, MapPin, Download, FileText, FileBadge, Factory, Cog, ClipboardCheck, Package, Truck, Clock, Wrench } from 'lucide-react';

// Static asset export: Next's RSC graph forbids react-dom/server at runtime.
// Use public Lucide components here; never redraw or copy reference-site paths.
const icons = { arrow: ArrowRight, mail: Mail, phone: Phone, 'map-pin': MapPin,
  download: Download, 'file-text': FileText, certificate: FileBadge, factory: Factory,
  cog: Cog, inspection: ClipboardCheck, package: Package, truck: Truck, clock: Clock, wrench: Wrench };
const packageFile = createRequire(import.meta.url).resolve('lucide-react/package.json');
const { version } = JSON.parse(await readFile(packageFile, 'utf8'));
const license = await readFile(path.join(path.dirname(packageFile), 'LICENSE'), 'utf8');
const svg = Object.fromEntries(Object.entries(icons).map(([name, component]) => [name,
  renderToStaticMarkup(createElement(component, { size: 20, strokeWidth: 1.75,
    'aria-hidden': true, focusable: 'false', 'data-system-rendered-icon': name }))]));
const entries = Object.entries(svg).map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`).join('\n');
await writeFile(new URL('../lib/code-site-icons.ts', import.meta.url), `// Generated by node scripts/generate-code-site-icons.mjs from lucide-react@${version} (ISC).
// Public component output; no model-authored geometry or visitor-side React runtime.
const icons = {\n${entries}\n} as const;
export const systemIconIds = Object.keys(icons);

export function systemIconSvg(name: string) {
  if (!Object.hasOwn(icons, name)) throw new Error(\`未登记系统图标：\${name}\`);
  return icons[name as keyof typeof icons];
}

// ISC permission and copyright travel with generated pages containing icons.
export const systemIconLicense = ${JSON.stringify('<!--\nLucide icons\n' + license + '-->')};
`, 'utf8');
console.log(`Exported ${Object.keys(svg).length} Lucide ${version} icons.`);
